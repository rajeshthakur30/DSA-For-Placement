// Find Vector Size
// .We can find the size(number of elements) of a vector using the size() function, like v.size().

#include <iostream>
#include <vector>
using namespace std;

int main() {
    vector<char> v = {'a', 'c', 'f', 'd', 'z'};

    // Finding size
    cout << v.size();
  
    return 0;
}